"""Personal memory: what is about the person rather than the project, shared by
every repository of theirs that opts in (`dreamer init --personal`).

Store: $DREAMER_HOME/personal (default ~/.dreamer/personal), with smaller
budgets than project memory. A dreaming pass in an opted-in repository edits
it under /memories/personal alongside the project store.

Isolation:
- Repositories that did not opt in never read or write it; nothing global is
  touched (no ~/.claude, ~/.codex or ~/.cursor files).
- It is injected only through local, uncommitted files of the opted-in
  repository, and never into a file git tracks:
    Claude Code -> CLAUDE.local.md (managed block)
    Codex       -> AGENTS.override.md (Codex reads it instead of AGENTS.md, so
                   it is generated as AGENTS.md + the personal block)
    Cursor      -> .cursor/rules/dreamer-personal.mdc (alwaysApply rule)
- Several repositories share the store, so applying to it takes a lock and
  a pass that saw a different version of it than it started from aborts.
"""

import json
import os
import re
import subprocess
from pathlib import Path
from typing import List, Optional

from dreamer import repo, store
from dreamer.config import MemoryConfig

VROOT = store.VIRTUAL_ROOT + "/personal"
MARKER_FILE = Path(repo.LOCAL_DIR) / "personal.json"
BEGIN = "<!-- dreamer:personal:begin (managed by dreamer; regenerated from your personal memory) -->"
END = "<!-- dreamer:personal:end -->"
OVERRIDE_HEADER = ("<!-- Generated by dreamer: AGENTS.md plus your personal memory, for Codex (which reads this file "
                   "instead of AGENTS.md). Edit AGENTS.md, not this file; it is regenerated. -->")
TARGET_FILES = {"claude": "CLAUDE.local.md", "codex": "AGENTS.override.md",
                "cursor": ".cursor/rules/dreamer-personal.mdc"}
_BLOCK = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.DOTALL)
_LINK = re.compile(r"(\[[^\]]*\]\()([^)\s]+)(\))")

PROMPT = """
This person also keeps personal memory, under /memories/personal/. It is their own, shared by every one of their repositories that opted in and never committed to any of them, and its MEMORY.md is injected into their sessions in all of those repositories. Put there only what is about the person and holds in any of their projects: how they like to work and to be answered, and how tools and services they use everywhere behave. Anything about this project, its code, its people or its clients stays in project memory; when unsure, keep it in the project. Personal pages link only to personal pages, project pages only to project pages."""


def home() -> Path:
    return Path(os.environ.get("DREAMER_HOME") or "~/.dreamer").expanduser()


# -- personal-only passes ---------------------------------------------------------
# Running dreamer with $DREAMER_HOME as its "repository" (`--personal`) dreams
# over the personal store itself: notes left from chat apps through the MCP
# server or `dreamer note --personal`, with no project and no transcripts.

PERSONAL_SYSTEM = """You maintain one person's own long-term memory. You run offline, between their sessions with AI agents and chat apps.

Every agent this person works with, in any of their projects that opted in and in chat apps, starts with MEMORY.md of this store in its context, and can open the other files when relevant. Your purpose is to make those future sessions waste less effort: fewer things the person has to repeat about themselves, how they like to work and to be answered, and how tools and services they use everywhere behave, and no acting on notes that are wrong.

A note is a prediction that it will matter again. Keep only what is about the person and holds across their projects; anything about one project, its code, its people or its clients does not belong here, even if a note asks for it. A wrong or stale note is worse than none. Record where a note came from, e.g. (2026-11-08, note), so later passes can re-check it.

MEMORY.md should stay a short, high-signal index plus one-line links to topic files (links relative to the linking file). A page nothing links to will never be found. The store has hard budgets; writes over budget are rejected, so make room by merging, condensing or deleting.

Make the smallest set of edits that serves the purpose. If nothing in these notes is worth remembering, change nothing. End with one line summarising what you changed and why."""


def is_root(root: Path) -> bool:
    try:
        return Path(root).resolve() == home().resolve()
    except OSError:
        return False


def adapt(root: Path, cfg):
    """Config for a personal-only pass: the personal store is the store."""
    if is_root(root):
        pc = config()
        pc.dir = "personal"
        cfg.memory = pc
        cfg.transcripts.sources = []
        cfg.dream.min_new_chars = min(cfg.dream.min_new_chars, 200)  # notes are explicit; few are enough
    return cfg


def store_dir() -> Path:
    return home() / "personal"


def config() -> MemoryConfig:
    return MemoryConfig(dir="", index_max_lines=60, index_max_bytes=4096, topic_max_bytes=8192,
                        store_max_bytes=64 * 1024, max_files=30)


def enabled(root: Path) -> bool:
    return (root / MARKER_FILE).is_file()


def harnesses(root: Path) -> List[str]:
    try:
        return list(json.loads((root / MARKER_FILE).read_text(encoding="utf-8")).get("harnesses", []))
    except (OSError, ValueError):
        return []


def ensure_store() -> Path:
    d = store_dir()
    d.mkdir(parents=True, exist_ok=True)
    idx = d / store.INDEX
    if not idx.exists():
        idx.write_text("# Personal memory\n", encoding="utf-8")
    return d


def lock():
    return repo.lock(ensure_store(), ".lock")


def tracked(root: Path, rel: str) -> bool:
    try:
        return subprocess.run(["git", "ls-files", "--error-unmatch", rel], cwd=root,
                              capture_output=True).returncode == 0
    except OSError:
        return False


def _block() -> str:
    d = store_dir()
    idx = d / store.INDEX
    text = idx.read_text(encoding="utf-8") if idx.exists() else ""
    text = re.sub(r"\A\s*# [^\n]*\n?", "", text)

    def absolute(m):
        t = m.group(2)
        if re.match(r"^[a-z]+:", t) or t.startswith(("#", "/")):
            return m.group(0)
        return f"{m.group(1)}{d / t}{m.group(3)}"

    text = re.sub(r"^(#+) ", r"#\1 ", _LINK.sub(absolute, text), flags=re.MULTILINE).strip()
    body = ("## Personal memory\n"
            f"This is your user's own memory, shared across their projects and kept in `{d}/` (never committed). "
            "It is about them, not this project; open a linked page when it matters, and if a note turns out wrong, "
            f"correct it in `{d}/`.")
    return f"{BEGIN}\n{body}" + (f"\n\n{text}" if text else "") + f"\n{END}"


def _render(root: Path, kind: str, current: str) -> str:
    block = _block()
    if kind == "codex":
        if current and not current.startswith(OVERRIDE_HEADER):  # the person's own override file
            return _BLOCK.sub(lambda _: block, current, count=1) if _BLOCK.search(current) else current.rstrip() + "\n\n" + block + "\n"
        agents = root / "AGENTS.md"
        base = agents.read_text(encoding="utf-8").strip() if agents.exists() else ""
        return OVERRIDE_HEADER + "\n" + (base + "\n\n" if base else "") + block + "\n"
    if kind == "cursor":
        return ("---\ndescription: This person's own memory, shared across their projects (dreamer)\n"
                "alwaysApply: true\n---\n" + block + "\n")
    if _BLOCK.search(current):
        return _BLOCK.sub(lambda _: block, current, count=1)
    return (current.rstrip() + "\n\n" if current.strip() else "") + block + "\n"


def sync(root: Path) -> List[str]:
    """Refresh the local copies. Skips (and reports) any target git tracks."""
    if not enabled(root):
        return []
    changed = []
    for kind in harnesses(root):
        rel = TARGET_FILES.get(kind)
        if not rel:
            continue
        if tracked(root, rel):
            repo.log(repo.state_dir(root), f"personal memory not written to {rel}: the file is tracked by git")
            continue
        path = root / rel
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        new = _render(root, kind, current)
        if new != current:
            repo.atomic_write(path, new)
            repo.exclude(root, rel)
            changed.append(rel)
    return changed


def enable(root: Path, kinds: List[str]) -> List[str]:
    out = []
    ensure_store()
    for k in kinds:
        rel = TARGET_FILES.get(k)
        if rel and tracked(root, rel):
            out.append(f"personal memory will not be injected for {k}: {rel} is tracked by git")
    unsupported = [k for k in kinds if k not in TARGET_FILES]
    if unsupported:
        out.append(f"personal memory has no local, uncommitted instruction file for: {', '.join(unsupported)}")
    repo.atomic_write(root / MARKER_FILE, json.dumps({"harnesses": [k for k in kinds if k in TARGET_FILES]}))
    for rel in sync(root):
        out.append(f"personal memory injected via {rel} (git-excluded)")
    out.append(f"personal store: {store_dir()}")
    return out


def disable(root: Path) -> List[str]:
    out = []
    for kind in harnesses(root):
        rel = TARGET_FILES.get(kind)
        path = root / rel if rel else None
        if not path or not path.exists() or tracked(root, rel):
            continue
        text = path.read_text(encoding="utf-8")
        if kind == "cursor" or text.startswith(OVERRIDE_HEADER):
            path.unlink()
        else:
            new = re.sub(r"\n*" + _BLOCK.pattern + r"\n?", "\n", text, flags=re.DOTALL).strip()
            if new:
                repo.atomic_write(path, new + "\n")
            else:
                path.unlink()
        out.append(f"removed personal memory from {rel}")
    (root / MARKER_FILE).unlink(missing_ok=True)
    out.append(f"personal store kept at {store_dir()}")
    return out


def stale(root: Path) -> List[str]:
    out = []
    for kind in harnesses(root):
        rel = TARGET_FILES.get(kind)
        if not rel or tracked(root, rel):
            continue
        path = root / rel
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if _render(root, kind, current) != current:
            out.append(rel)
    return out


def staging(sdir: Path) -> Path:
    return sdir / "staging-personal"


def tool(sdir: Path) -> Optional[store.MemoryTool]:
    d = staging(sdir)
    return store.MemoryTool(d, config(), VROOT) if d.is_dir() else None
